#!/usr/bin/env node
/**
 * Prepare .env.local for production integrations.
 * Generates Strava/crypto secrets; sets Supabase URL + app URL; does NOT overwrite existing secrets.
 */
import { randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENV_FILES = [path.join(ROOT, ".env.local"), path.join(ROOT, "apps/web/.env.local")];

const SUPABASE_PROJECT = "beuiammeedpovdkmhluw";
const PRODUCTION_APP_URL = "https://fitconnect-phi.vercel.app";

function parseEnv(content) {
  const lines = content.split(/\r?\n/);
  const map = new Map();
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    map.set(trimmed.slice(0, eq).trim(), trimmed);
  }
  return { lines, map };
}

function quote(val) {
  if (/[\s#"]/.test(val)) return `"${val.replace(/"/g, '\\"')}"`;
  return val;
}

function getOrGenerate(map, key, generator) {
  const existing = map.get(key);
  if (existing) {
    const val = existing.split("=").slice(1).join("=").trim().replace(/^["']|["']$/g, "");
    if (val && !val.includes("your-") && val.length > 3) return null;
  }
  return generator();
}

function secretHex(bytes = 32) {
  return randomBytes(bytes).toString("hex");
}

function webhookToken() {
  return `fc_${randomBytes(18).toString("base64url")}`;
}

const DEFAULTS = [
  ["# FitConnect — production env (generated by setup-production-env.mjs)", null],
  ["", null],
  ["# ── Supabase (beuiammeedpovdkmhluw) ──", null],
  ["NEXT_PUBLIC_SUPABASE_URL", `https://${SUPABASE_PROJECT}.supabase.co`],
  ["NEXT_PUBLIC_SUPABASE_ANON_KEY", "PASTE_ANON_KEY_FROM_SUPABASE_API_SETTINGS"],
  ["SUPABASE_SERVICE_ROLE_KEY", "PASTE_SERVICE_ROLE_FROM_SUPABASE_API_SETTINGS"],
  [
    "DATABASE_URL",
    `postgresql://postgres.${SUPABASE_PROJECT}:PASTE_DB_PASSWORD@aws-0-eu-west-1.pooler.supabase.com:6543/postgres?pgbouncer=true`
  ],
  [
    "DIRECT_URL",
    `postgresql://postgres.${SUPABASE_PROJECT}:PASTE_DB_PASSWORD@db.${SUPABASE_PROJECT}.supabase.co:5432/postgres`
  ],
  ["", null],
  ["NEXT_PUBLIC_DEMO_MODE", "false"],
  ["NEXT_PUBLIC_APP_URL", PRODUCTION_APP_URL],
  ["", null],
  ["# ── Realtime (keep Convex; auth via Supabase) ──", null],
  ["NEXT_PUBLIC_REALTIME_PROVIDER", "convex"],
  ["NEXT_PUBLIC_CONVEX_URL", "https://valuable-camel-828.convex.cloud"],
  ["", null],
  ["# ── Stripe (live) ──", null],
  ["STRIPE_SECRET_KEY", "PASTE_sk_live_OR_sk_test"],
  ["NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY", "PASTE_pk_live_OR_pk_test"],
  ["STRIPE_WEBHOOK_SECRET", "PASTE_whsec_FROM_STRIPE_WEBHOOK"],
  ["", null],
  ["# ── Strava ──", null],
  ["STRAVA_CLIENT_ID", "PASTE_STRAVA_CLIENT_ID"],
  ["STRAVA_CLIENT_SECRET", "PASTE_STRAVA_CLIENT_SECRET"],
  ["STRAVA_WEBHOOK_VERIFY_TOKEN", null],
  ["STRAVA_TOKEN_ENCRYPTION_KEY", null],
  ["STRAVA_OAUTH_STATE_SECRET", null],
  ["", null],
  ["# ── Upstash Redis ──", null],
  ["UPSTASH_REDIS_REST_URL", "PASTE_UPSTASH_REDIS_REST_URL"],
  ["UPSTASH_REDIS_REST_TOKEN", "PASTE_UPSTASH_REDIS_REST_TOKEN"],
  ["", null],
  ["# ── Analytics ──", null],
  ["NEXT_PUBLIC_POSTHOG_KEY", "PASTE_phc_POSTHOG_KEY"],
  ["NEXT_PUBLIC_POSTHOG_HOST", "https://app.posthog.com"],
  ["NEXT_PUBLIC_SENTRY_DSN", "PASTE_SENTRY_DSN"],
  ["", null],
  ["# ── Convex (local dev) ──", null],
  ["CONVEX_DEPLOYMENT", "dev:valuable-camel-828"],
  ["CONVEX_SITE_URL", "https://valuable-camel-828.convex.site"]
];

for (const envFile of ENV_FILES) {
  const existing = fs.existsSync(envFile) ? fs.readFileSync(envFile, "utf8") : "";
  const { map } = parseEnv(existing);

  const stravaWebhook =
    getOrGenerate(map, "STRAVA_WEBHOOK_VERIFY_TOKEN", webhookToken) ??
    map.get("STRAVA_WEBHOOK_VERIFY_TOKEN")?.split("=").slice(1).join("=").replace(/^["']|["']$/g, "");
  const stravaEnc =
    getOrGenerate(map, "STRAVA_TOKEN_ENCRYPTION_KEY", () => secretHex(32)) ??
    map.get("STRAVA_TOKEN_ENCRYPTION_KEY")?.split("=").slice(1).join("=").replace(/^["']|["']$/g, "");
  const stravaOAuth =
    getOrGenerate(map, "STRAVA_OAUTH_STATE_SECRET", () => secretHex(32)) ??
    map.get("STRAVA_OAUTH_STATE_SECRET")?.split("=").slice(1).join("=").replace(/^["']|["']$/g, "");

  const out = [];
  for (const [key, defaultVal] of DEFAULTS) {
    if (defaultVal === null && key.startsWith("#")) {
      out.push(key);
      continue;
    }
    if (defaultVal === null && !key.startsWith("#")) {
      out.push("");
      continue;
    }

    let val = defaultVal;
    if (key === "STRAVA_WEBHOOK_VERIFY_TOKEN") val = stravaWebhook;
    if (key === "STRAVA_TOKEN_ENCRYPTION_KEY") val = stravaEnc;
    if (key === "STRAVA_OAUTH_STATE_SECRET") val = stravaOAuth;

    const existingLine = map.get(key);
    if (existingLine) {
      const existingVal = existingLine.split("=").slice(1).join("=").trim().replace(/^["']|["']$/g, "");
      const isPlaceholder =
        !existingVal ||
        existingVal.includes("your-") ||
        existingVal.includes("PASTE_") ||
        existingVal === "postgresql://user:pass@host/fitconnect?sslmode=require";
      if (!isPlaceholder && !key.startsWith("STRAVA_")) {
        out.push(existingLine);
        continue;
      }
      if (
        key.startsWith("STRAVA_") &&
        existingVal &&
        !existingVal.includes("PASTE") &&
        existingVal !== "fitconnect-dev"
      ) {
        out.push(existingLine);
        continue;
      }
    }

    out.push(`${key}=${quote(String(val))}`);
  }

  fs.mkdirSync(path.dirname(envFile), { recursive: true });
  fs.writeFileSync(envFile, `${out.join("\n")}\n`, "utf8");
  console.log("Updated:", envFile);
}

console.log("\nRun: node scripts/validate-env.mjs");
console.log("Supabase API keys: https://supabase.com/dashboard/project/beuiammeedpovdkmhluw/settings/api");
