#!/usr/bin/env node
/**
 * generate-kotlin-tokens.mjs — Elite Surface (ADR-007) token generator.
 *
 * Parses COLOR_TOKENS from packages/design-tokens/index.ts and emits a
 * dependency-free Kotlin object (ARGB Long constants) for native Android:
 *   android/design/src/main/kotlin/com/fitconnect/android/design/EliteSurfaceTokens.kt
 *
 * Usage:
 *   node scripts/generate-kotlin-tokens.mjs          # (re)write the Kotlin file
 *   node scripts/generate-kotlin-tokens.mjs --check  # exit 1 if file on disk drifted
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "packages", "design-tokens", "index.ts");
const OUTPUT = path.join(
  ROOT,
  "android",
  "design",
  "src",
  "main",
  "kotlin",
  "com",
  "fitconnect",
  "android",
  "design",
  "EliteSurfaceTokens.kt"
);

function fail(message) {
  console.error(`[tokens:kotlin] ERROR: ${message}`);
  process.exit(1);
}

/** camelCase / camel123 token key → SCREAMING_SNAKE (voltlineDim → VOLTLINE_DIM, volt300 → VOLT_300). */
function toConstName(key) {
  return key
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([a-zA-Z])(\d)/g, "$1_$2")
    .toUpperCase();
}

/** CSS colour value → 8-digit uppercase ARGB hex string (no 0x prefix). */
function toArgbHex(value, key) {
  if (value.startsWith("#")) {
    let hex = value.slice(1).toLowerCase();
    if (!/^[0-9a-f]+$/.test(hex)) fail(`invalid hex "${value}" for token "${key}"`);
    if (hex.length === 3 || hex.length === 4) {
      hex = [...hex].map((c) => c + c).join("");
    }
    if (hex.length === 6) return `FF${hex.toUpperCase()}`;
    if (hex.length === 8) {
      // CSS is #RRGGBBAA — Kotlin/Android wants AARRGGBB.
      return (hex.slice(6, 8) + hex.slice(0, 6)).toUpperCase();
    }
    fail(`unsupported hex length in "${value}" for token "${key}"`);
  }

  const rgba = value.match(
    /^rgba?\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})\s*(?:,\s*([\d.]+)\s*)?\)$/
  );
  if (rgba) {
    const [, r, g, b, a] = rgba;
    const alpha = a === undefined ? 255 : Math.round(parseFloat(a) * 255);
    const channels = [alpha, Number(r), Number(g), Number(b)];
    if (channels.some((c) => !Number.isFinite(c) || c < 0 || c > 255)) {
      fail(`channel out of range in "${value}" for token "${key}"`);
    }
    return channels
      .map((c) => c.toString(16).padStart(2, "0"))
      .join("")
      .toUpperCase();
  }

  fail(`cannot convert value "${value}" for token "${key}" to ARGB`);
}

/** Extract [key, cssValue] pairs from the COLOR_TOKENS object literal. */
function parseColorTokens(tsSource) {
  const objectMatch = tsSource.match(
    /export const COLOR_TOKENS = \{([\s\S]*?)\}\s*as const;/
  );
  if (!objectMatch) fail(`could not locate COLOR_TOKENS in ${SOURCE}`);

  const entries = [];
  for (const rawLine of objectMatch[1].split("\n")) {
    const line = rawLine.trim();
    if (line === "" || line.startsWith("//") || line.startsWith("/*")) continue;
    const entry = line.match(/^([A-Za-z_$][\w$]*)\s*:\s*"([^"]+)"\s*,?$/);
    if (!entry) fail(`unparseable COLOR_TOKENS line: "${line}"`);
    entries.push([entry[1], entry[2]]);
  }
  if (entries.length === 0) fail("parsed zero tokens from COLOR_TOKENS");
  return entries;
}

function generateKotlin() {
  const tsSource = fs.readFileSync(SOURCE, "utf8");
  const tokens = parseColorTokens(tsSource);

  const consts = tokens
    .map(([key, value]) => ({
      name: toConstName(key),
      argb: toArgbHex(value, key),
    }))
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

  const lines = [
    "// GENERATED by scripts/generate-kotlin-tokens.mjs — do not edit. Run: pnpm tokens:kotlin",
    "package com.fitconnect.android.design",
    "",
    "/**",
    " * Elite Surface colour tokens (ADR-007), mirrored from",
    " * packages/design-tokens COLOR_TOKENS. ARGB Long values, zero dependencies —",
    " * mapping to androidx.compose.ui.graphics.Color happens at the theme layer.",
    " */",
    "object EliteSurfaceColors {",
    ...consts.map((c) => `    const val ${c.name}: Long = 0x${c.argb}L`),
    "}",
    "",
  ];
  return lines.join("\n");
}

const checkMode = process.argv.includes("--check");
const generated = generateKotlin();

if (checkMode) {
  if (!fs.existsSync(OUTPUT)) {
    fail(`${path.relative(ROOT, OUTPUT)} missing — run: pnpm tokens:kotlin`);
  }
  const onDisk = fs.readFileSync(OUTPUT, "utf8").replace(/\r\n/g, "\n");
  if (onDisk !== generated) {
    fail(
      `${path.relative(ROOT, OUTPUT)} is out of date with packages/design-tokens — run: pnpm tokens:kotlin`
    );
  }
  console.log("[tokens:kotlin] check OK — EliteSurfaceTokens.kt is in sync");
} else {
  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, generated, "utf8");
  console.log(
    `[tokens:kotlin] wrote ${path.relative(ROOT, OUTPUT)} (${generated.split("\n").length - 1} lines)`
  );
}
